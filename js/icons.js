/** Returns a new <svg> element for the named icon (empty svg for unknown names). */
export function icon(name, size = 16) {
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');
  svg.classList.add('ico');
  svg.innerHTML = PATHS[name] ?? ''; // static strings above, never user data
  return svg;
}

/** Prepends the icon named by data-icon to every [data-icon] element under root. */
export function decorate(root = document) {
  for (const n of root.querySelectorAll('[data-icon]')) {
    if (!n.querySelector('.ico')) n.prepend(icon(n.dataset.icon, Number(n.dataset.iconSize) || 16));
  }
}
